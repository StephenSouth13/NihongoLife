"""Rebuild the persisted classroom lesson -> uploaded URL map, UTF-8 and explicit IDs only.
Run from repo root: python NihongoLife/Tools/classroom/build_lesson_videos.py
School IDs are never guessed from course ordering. A path `ref` is the curriculum mapping authority.
"""
from pathlib import Path
from collections import Counter
import json, re, sys
ROOT = Path(__file__).resolve().parents[3]
R = ROOT / 'NihongoLife/Assets/NihongoLife/Resources'
def read(p): return json.loads(p.read_text(encoding='utf-8-sig'))
def write(p, val): p.parent.mkdir(parents=True, exist_ok=True);p.write_text(json.dumps(val, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
def youtube_id(url):
 m = re.search(r'(?:youtube\.com/(?:watch\?(?:.*&)?v=|embed/)|youtu\.be/)([A-Za-z0-9_-]{11})(?![\w-])', url or '')
 return m.group(1) if m else None
links, seen = [], set()
def add(target, kind, id, step, video, url, title, source):
 if not youtube_id(url): raise ValueError(f'{source}: {step}: unusable YouTube URL {url}')
 key = (target, kind, id, youtube_id(url))
 if key in seen: return
 seen.add(key)
 item = dict(target=target, kind=kind, id=id, videoId=youtube_id(url), youtubeUrl=url, stepId=step, source=source, title=title)
 if not item['title'].get('ru'): item['title']['ru'] = item['title'].get('en') or item['title'].get('vi')
 links.append(item)
path = read(R / 'Content/Russian/ru_path.json')
steps = [s for stage in path['stages'] for s in stage['steps']]
for s in steps:
 v = s.get('video') or {}
 if not (v.get('id') and youtube_id(v.get('youtubeUrl'))) or s['kind'] == 'mock': continue
 id = ('cert_' + s['ref']) if s['kind'] == 'cert' else 'ru_pronunciation' if s['kind'] == 'pronunciation' else s['ref']
 if s['kind'] == 'cert':
  add('ru', 'exam', s['ref'] + '_mock_1', s['id'], v['id'], v['youtubeUrl'], s['title'], 'ru_path.json')
 if s['id'] == 'ru_L_4a':
  for part in ('ru_ar_consonants_1','ru_ar_consonants_2','ru_ar_consonants_3'):
   add('ru', 'alphabet', part, s['id'], v['id'], v['youtubeUrl'], s['title'], 'ru_path.json')
 add('ru', s['kind'], id, s['id'], v['id'], v['youtubeUrl'], s['title'], 'ru_path.json')
plan = read(R / 'Content/English/english_upload_plan.json')
for v in plan['videos']:
 if not (v.get('uploaded') and youtube_id(v.get('youtubeUrl'))): continue
 title = {'vi':v['titleVi'],'en':v['titleEn'],'ja':v['titleEn']}
 # School has exactly one authored English phonics alphabet. Course numbering is NOT a School unit number.
 add('en', 'alphabet' if v['step']=='en_01' else 'collection', 'en_phonics' if v['step']=='en_01' else 'en_course_'+v['step'], v['step'], v['step'], v['youtubeUrl'], title, 'english_upload_plan.json')
library = read(R / 'Video/video_courses.json')
english = next(c for c in library['courses'] if c['id'] == 'english')
english['titleVi'] = 'Tiếng Anh – các bài đã đăng'
english['titleEn'] = 'Uploaded English lessons'
english['sections'][0] = {'title':'Bài học tiếng Anh','titleEn':'English lessons','titleJa':'英語','lessons':[]}
for v in plan['videos']:
 if v.get('uploaded') and youtube_id(v.get('youtubeUrl')):
  english['sections'][0]['lessons'].append({'id':youtube_id(v['youtubeUrl']), 'title':v['titleVi'], 'seconds':round(v['durationSec'])})
for c in library['courses']:
 if c['lang'] in ('ru','all'): continue
 for sec in c['sections']:
  for clip in sec['lessons']:
   title = {'vi':clip['title'],'en':clip['title'],'ja':clip['title']}
   id = clip['id']
   # IELTS uploads are grouped by topic in English Video Series, not assigned to an unrelated practice certificate.
   # Japanese uploads retain varying Japanese course-topic IDs; the patterns below have precise set IDs.
   key = 'ja_course_'+id if c['lang']=='ja' else 'ielts_course_'+id
   add(c['lang'], 'collection', key, id, id, 'https://youtu.be/'+id, title, 'video_courses.json')
japanese = next(c for c in library['courses'] if c['id']=='japanese')
for sec in japanese['sections']:
 for clip in sec['lessons']:
  if clip['id'].startswith('jp_pattern_') or clip['id']=='ja_patterns':
   title = {'vi':clip['title'],'en':clip['title'],'ja':clip['title']}
   add('ja','grammar',clip['id'],clip['id'],clip['id'],'https://youtu.be/'+clip['id'],title,'video_courses.json')
write(R / 'Content/Video/lesson_video_index.json', {'schema':'nihongolife.lesson_videos.v1','note':'Generated by Tools/classroom/build_lesson_videos.py. Explicit curriculum references; no copyrighted course text or credentials.','links':links})
write(R / 'Video/video_courses.json', library)
print(f'Generated {len(links)} index rows', Counter((x['target'],x['kind']) for x in links))
