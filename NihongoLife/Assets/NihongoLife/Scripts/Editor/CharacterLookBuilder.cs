    /// <summary>
    /// Measures the Kids-pack models for <see cref="CharacterLook"/> and bakes what it needs into
    /// Resources/Characters/Looks: per model the hair colour, a hair mask on its atlas (the head's triangles that wear
    /// the hair colour), the skin colour and the face in head-bone space (mouth, forward, up, width) for the beard and
    /// the wrinkles (looks.json); the hair-recolour blit material and the beard material.
    /// Run: Unity -batchmode -executeMethod NihongoLife.EditorTools.CharacterLookBuilder.Build
    /// </summary>
    public static class CharacterLookBuilder
    {
        private const string Folder = "Assets/NihongoLife/Resources/Characters/Looks/";

        public static void Build()
        {
            try
            {
                Directory.CreateDirectory(Folder);
                var models = new List<LookModel>();
                var log = new StringBuilder();
                foreach (var (model, id) in KidsCharactersSetup.Kids)
                {
                    var look = Measure(model, id, log);
                    if (look != null) models.Add(look);
                }
                File.WriteAllText(Folder + "looks.json", JsonUtility.ToJson(new LookModels { schema = "nihongolife.look-models.v1 (generated by CharacterLookBuilder — do not edit)", models = models.ToArray() }, true));
                BuildMaterials();
                AssetDatabase.Refresh();
                foreach (var m in models) ConfigureMask(Folder + m.mask + ".png");
                AssetDatabase.SaveAssets();
                Debug.Log("[CharacterLook] " + models.Count + " models\n" + log);
            }
            catch (Exception e)
            {
                Debug.LogException(e);
                if (Application.isBatchMode) EditorApplication.Exit(1);
            }
            if (Application.isBatchMode) EditorApplication.Exit(0);
        }

        private static LookModel Measure(string model, string id, StringBuilder log)
        {
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(KidsCharactersSetup.PrefabFolder + "NL_" + id + ".prefab");
            if (prefab == null) { log.AppendLine(id + ": no prefab"); return null; }
            var instance = (GameObject)PrefabUtility.InstantiatePrefab(prefab);
            try
            {
                instance.transform.SetPositionAndRotation(Vector3.zero, Quaternion.identity);
                var animator = instance.GetComponentInChildren<Animator>(true);
                var head = animator != null ? animator.GetBoneTransform(HumanBodyBones.Head) : null;
                var smr = instance.GetComponentsInChildren<SkinnedMeshRenderer>(true).OrderByDescending(r => r.sharedMesh != null ? r.sharedMesh.vertexCount : 0).FirstOrDefault();
                if (head == null || smr == null) { log.AppendLine(id + ": no head / mesh"); return null; }
                log.AppendLine(id + " renderers: " + string.Join(", ", instance.GetComponentsInChildren<Renderer>(true).Select(r => $"{r.name}[{(r is SkinnedMeshRenderer s ? s.sharedMesh.vertexCount : 0)}] {r.sharedMaterial?.name} sub={(r is SkinnedMeshRenderer s2 ? s2.sharedMesh.subMeshCount : 0)}")));
                var material = smr.sharedMaterial;
                var atlas = material.GetTexture("_Texture2D") as Texture2D;
                var pixels = ReadPng(AssetDatabase.GetAssetPath(atlas));
                if (pixels == null) { log.AppendLine(id + ": atlas unreadable"); return null; }

                var mesh = smr.sharedMesh;
                var baked = new Mesh();
                smr.BakeMesh(baked, false); // already at the renderer's scale (the kid's 1.35× root): only move and turn it
                var t = smr.transform;
                var world = baked.vertices.Select(v => t.position + t.rotation * v).ToArray();
                UnityEngine.Object.DestroyImmediate(baked);
                var uv = mesh.uv;
                var headBones = new HashSet<int>();
                for (int b = 0; b < smr.bones.Length; b++) if (smr.bones[b] != null && smr.bones[b].IsChildOf(head)) headBones.Add(b);
                var weights = mesh.boneWeights;
                bool[] onHead = new bool[world.Length];
                for (int i = 0; i < world.Length; i++)
                {
                    var w = weights[i];
                    float sum = (headBones.Contains(w.boneIndex0) ? w.weight0 : 0f) + (headBones.Contains(w.boneIndex1) ? w.weight1 : 0f)
                              + (headBones.Contains(w.boneIndex2) ? w.weight2 : 0f) + (headBones.Contains(w.boneIndex3) ? w.weight3 : 0f);
                    // The head's own vertices, and everything above the neck (some models weight the hair to other bones).
                    // (not the T-posed arms, which are at neck height too)
                    onHead[i] = sum > 0.5f || (world[i].y > head.position.y + 0.02f && Mathf.Abs(world[i].x - head.position.x) < 0.4f);
                }
                var headIdx = Enumerable.Range(0, world.Length).Where(i => onHead[i]).ToArray();
                Vector3 min = Vector3.positiveInfinity, max = Vector3.negativeInfinity;
                foreach (int i in headIdx) { min = Vector3.Min(min, world[i]); max = Vector3.Max(max, world[i]); }
                Vector3 size = max - min, centre = (min + max) * 0.5f;

                Color32 Texel(int i)
                {
                    int x = Mathf.Clamp(Mathf.FloorToInt(Mathf.Repeat(uv[i].x, 1f) * pixels.width), 0, pixels.width - 1);
                    int y = Mathf.Clamp(Mathf.FloorToInt(Mathf.Repeat(uv[i].y, 1f) * pixels.height), 0, pixels.height - 1);
                    return pixels.data[y * pixels.width + x];
                }
                Color32 Mode(IEnumerable<int> indices) => indices.Select(Texel).GroupBy(c => (c.r, c.g, c.b)).OrderByDescending(g => g.Count()).Select(g => g.First()).FirstOrDefault();

                // Hair: the colour on the top of the head. Skin: the front of the lower face.
                // (the very top only: some heads hide a skin scalp just under the hair shell)
                var hair = Mode(headIdx.Where(i => world[i].y > max.y - size.y * 0.04f));
                // Skin: the commonest bright colour of the head that is not the hair (eyes and brows are dark).
                // The face is the front surface of the head (kids face +Z); its lowest point is the chin (the neck
                // below sits further back), the mouth a little above it.
                float faceFrontZ = headIdx.Where(i => Mathf.Abs(world[i].x - centre.x) < 0.1f && world[i].y < centre.y).Select(i => world[i].z).DefaultIfEmpty(max.z).Max();
                var face = headIdx.Where(i => world[i].z > faceFrontZ - 0.07f && Mathf.Abs(world[i].x - centre.x) < 0.14f).ToArray();
                float chinY = face.Length > 0 ? face.Min(i => world[i].y) : min.y;
                float mouthY = chinY + size.y * 0.08f;
                var band = headIdx.Where(i => Mathf.Abs(world[i].y - mouthY) < size.y * 0.05f && Mathf.Abs(world[i].x - centre.x) < 0.1f).ToArray();
                float frontZ = band.Select(i => world[i].z).DefaultIfEmpty(faceFrontZ).Max();
                // Skin: the commonest colour of the lower face that is neither hair nor the dark eyes / brows.
                int[] SkinOf(int floor) => face.Where(i => { var c = Texel(i); return world[i].y < chinY + size.y * 0.25f && !Near(c, hair) && c.r + c.g + c.b > floor; }).ToArray();
                var lower = SkinOf(200);
                var skin = Mode(lower.Length > 0 ? lower : SkinOf(90));
                // The jaw: the front half of the head just above the chin (not the hair hanging at the sides).
                var jaw = headIdx.Where(i => world[i].y >= chinY && world[i].y <= chinY + size.y * 0.2f && world[i].z > faceFrontZ - 0.16f && !Near(Texel(i), hair)).ToArray();
                float width = jaw.Length > 0 ? jaw.Max(i => world[i].x) - jaw.Min(i => world[i].x) : size.x;
                var mouth = head.InverseTransformPoint(new Vector3(centre.x, mouthY, frontZ));

                // The hair mask: texels of the hair colour inside the head's triangles that wear it.
                var mask = new byte[pixels.width * pixels.height];
                var tris = mesh.triangles;
                int hairTris = 0;
                for (int k = 0; k < tris.Length; k += 3)
                {
                    int a = tris[k], b = tris[k + 1], c = tris[k + 2];
                    if (!onHead[a] || !onHead[b] || !onHead[c]) continue;
                    if (!Near(Texel(a), hair) && !Near(Texel(b), hair) && !Near(Texel(c), hair)) continue;
                    hairTris++;
                    Rasterize(uv[a], uv[b], uv[c], pixels, hair, mask);
                }
                string maskName = "hairmask_" + model.ToLowerInvariant();
                var maskTexture = new Texture2D(pixels.width, pixels.height, TextureFormat.RGB24, false);
                maskTexture.SetPixels32(mask.Select(m => new Color32(m, m, m, 255)).ToArray());
                File.WriteAllBytes(Folder + maskName + ".png", maskTexture.EncodeToPNG());
                UnityEngine.Object.DestroyImmediate(maskTexture);

                float scale = head.lossyScale.x;
                float allTop = world.Max(v => v.y);
                log.AppendLine($"   head bone {head.position} lossy {head.lossyScale.x} | headverts y {min.y:0.000}..{max.y:0.000} z {min.z:0.000}..{max.z:0.000} | faceFront {faceFrontZ:0.000} chin {chinY:0.000} mouthY {mouthY:0.000} frontZ {frontZ:0.000} | top of mesh {allTop:0.000} smr lossy {t.lossyScale} root {instance.transform.localScale}");
                log.AppendLine($"{id} ({model}): hair #{ColorUtility.ToHtmlStringRGB(hair)} skin #{ColorUtility.ToHtmlStringRGB(skin)} head {size} face width {width:0.000} (head scale {scale:0.###}) mouth {mouth.x:0.####},{mouth.y:0.####},{mouth.z:0.####} fwd {head.InverseTransformDirection(Vector3.forward)} hair tris {hairTris} mask {mask.Count(m => m > 0)} px");
                return new LookModel
                {
                    model = model,
                    texture = atlas.name,
                    mask = maskName,
                    hairHex = "#" + ColorUtility.ToHtmlStringRGB(hair),
                    skinHex = "#" + ColorUtility.ToHtmlStringRGB(skin),
                    boy = model.StartsWith("Boy", StringComparison.Ordinal),
                    forward = Arr(head.InverseTransformDirection(Vector3.forward).normalized),
                    up = Arr(head.InverseTransformDirection(Vector3.up).normalized),
                    mouth = Arr(mouth),
                    faceWidth = width / Mathf.Max(0.0001f, scale),
                };
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(instance);
            }
        }

        private sealed class Pixels { public int width, height; public Color32[] data; }

        private static Pixels ReadPng(string path)
        {
            if (string.IsNullOrEmpty(path) || !File.Exists(path)) return null;
            var texture = new Texture2D(2, 2, TextureFormat.RGBA32, false);
            if (!texture.LoadImage(File.ReadAllBytes(path))) return null;
            var pixels = new Pixels { width = texture.width, height = texture.height, data = texture.GetPixels32() };
            UnityEngine.Object.DestroyImmediate(texture);
            return pixels;
        }

        private static bool Near(Color32 a, Color32 b) => Mathf.Abs(a.r - b.r) <= 6 && Mathf.Abs(a.g - b.g) <= 6 && Mathf.Abs(a.b - b.b) <= 6;

        private static void Rasterize(Vector2 a, Vector2 b, Vector2 c, Pixels pixels, Color32 hair, byte[] mask)
        {
            Vector2 P(Vector2 v) => new Vector2(Mathf.Repeat(v.x, 1f) * pixels.width, Mathf.Repeat(v.y, 1f) * pixels.height);
            Vector2 pa = P(a), pb = P(b), pc = P(c);
            int x0 = Mathf.Max(0, Mathf.FloorToInt(Mathf.Min(pa.x, pb.x, pc.x)) - 1), x1 = Mathf.Min(pixels.width - 1, Mathf.CeilToInt(Mathf.Max(pa.x, pb.x, pc.x)) + 1);
            int y0 = Mathf.Max(0, Mathf.FloorToInt(Mathf.Min(pa.y, pb.y, pc.y)) - 1), y1 = Mathf.Min(pixels.height - 1, Mathf.CeilToInt(Mathf.Max(pa.y, pb.y, pc.y)) + 1);
            float area = (pb.x - pa.x) * (pc.y - pa.y) - (pc.x - pa.x) * (pb.y - pa.y);
            bool degenerate = Mathf.Abs(area) < 1e-4f;
            for (int y = y0; y <= y1; y++)
                for (int x = x0; x <= x1; x++)
                {
                    int i = y * pixels.width + x;
                    if (mask[i] != 0 || !Near(pixels.data[i], hair)) continue;
                    if (!degenerate)
                    {
                        var p = new Vector2(x + 0.5f, y + 0.5f);
                        float w0 = ((pb.x - p.x) * (pc.y - p.y) - (pc.x - p.x) * (pb.y - p.y)) / area;
                        float w1 = ((pc.x - p.x) * (pa.y - p.y) - (pa.x - p.x) * (pc.y - p.y)) / area;
                        float w2 = 1f - w0 - w1;
                        const float edge = -0.08f; // one texel of slack at the triangle's edges
                        if (w0 < edge || w1 < edge || w2 < edge) continue;
                    }
                    mask[i] = 255;
                }
        }

        private static void BuildMaterials()
        {
            var shader = Shader.Find("Hidden/NihongoLife/HairRecolor");
            if (shader == null) throw new Exception("Hidden/NihongoLife/HairRecolor shader not found");
            Save(new Material(shader) { name = "NL_HairRecolor" }, Folder + "NL_HairRecolor.mat");
            var lit = Shader.Find("Universal Render Pipeline/Lit");
            var beard = new Material(lit) { name = "NL_LookBeard" };
            beard.SetColor("_BaseColor", new Color(0.3f, 0.22f, 0.16f));
            beard.SetFloat("_Smoothness", 0.12f);
            Save(beard, Folder + "NL_LookBeard.mat");
        }

        private static void Save(Material material, string path)
        {
            var existing = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (existing != null) { existing.shader = material.shader; existing.CopyPropertiesFromMaterial(material); EditorUtility.SetDirty(existing); }
            else AssetDatabase.CreateAsset(material, path);
        }

        private static void ConfigureMask(string path)
        {
            var importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) return;
            importer.textureType = TextureImporterType.SingleChannel;
            var settings = new TextureImporterSettings();
            importer.ReadTextureSettings(settings);
            settings.singleChannelComponent = TextureImporterSingleChannelComponent.Red;
            importer.SetTextureSettings(settings);
            importer.sRGBTexture = false;
            importer.mipmapEnabled = false;
            importer.filterMode = FilterMode.Point;
            importer.textureCompression = TextureImporterCompression.Uncompressed;
            importer.isReadable = false;
            importer.SaveAndReimport();
        }

        private static float[] Arr(Vector3 v) => new[] { v.x, v.y, v.z };
    }
