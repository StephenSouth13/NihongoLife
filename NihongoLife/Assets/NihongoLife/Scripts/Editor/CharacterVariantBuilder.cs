    /// <summary>
    /// Builds the town's people from the Kids family (headless, no menu item):
    /// 1. measures every Kids model's atlas (the flat colour blocks of its skin, top and bottom, found through the
    ///    bones that wear them) into Resources/Characters/Variants/variant_models.json and the palette-recolour material;
    /// 2. turns Resources/Characters/variants.json into one prefab per person, Resources/Characters/Variants/NL_var_&lt;id&gt;:
    ///    the Kids prefab with its own proportions (height, girth), a <see cref="CharacterVariant"/> (hair, beard, age,
    ///    skin, top and bottom colours are applied at runtime by <see cref="CharacterLook"/>) and the uniform's props
    ///    (hats, ties, aprons ...) parented to the bones, so they follow every animation.
    /// Run: Unity -batchmode -executeMethod NihongoLife.EditorTools.CharacterVariantBuilder.Build
    /// </summary>
    public static class CharacterVariantBuilder
    {
        private const string Folder = "Assets/NihongoLife/Resources/Characters/Variants/";
        private const string VariantsPath = "Assets/NihongoLife/Resources/Characters/variants.json";

        public static void Build()
        {
            try
            {
                var log = new StringBuilder();
                Directory.CreateDirectory(Folder);
                Directory.CreateDirectory(Folder + "Materials");
                var file = JsonUtility.FromJson<CharacterVariantFile>(File.ReadAllText(VariantsPath));
                if (file == null || file.variants.Length == 0) throw new Exception("variants.json is empty");
                var palettes = KidsCharactersSetup.Kids.Select(k => MeasurePalette(k.model, k.id, log)).ToArray();
                File.WriteAllText(Folder + "variant_models.json", JsonUtility.ToJson(new LookPalettes { schema = "nihongolife.look-palettes.v1 (generated by CharacterVariantBuilder - do not edit)", models = palettes }, true));
                BuildMaterial();
                AssetDatabase.Refresh();
                BuildPrefabs(file, log);
                AssetDatabase.SaveAssets();
                Debug.Log("[CharacterVariants] " + file.variants.Length + " people, " + file.uniforms.Length + " uniforms\n" + log);
            }
            catch (Exception e)
            {
                Debug.LogException(e);
                if (Application.isBatchMode) EditorApplication.Exit(1);
                return;
            }
            if (Application.isBatchMode) EditorApplication.Exit(0);
        }

        // ----------------------------------------------------------------------------------------------- palettes

        private sealed class Atlas { public int width, height; public Color32[] data; }

        private static Atlas ReadAtlas(string path)
        {
            var texture = new Texture2D(2, 2, TextureFormat.RGBA32, false);
            if (!texture.LoadImage(File.ReadAllBytes(path))) throw new Exception("Cannot read " + path);
            var atlas = new Atlas { width = texture.width, height = texture.height, data = texture.GetPixels32() };
            UnityEngine.Object.DestroyImmediate(texture);
            return atlas;
        }

        private static bool Near(Color32 a, Color32 b, int tolerance = 14) => Mathf.Abs(a.r - b.r) <= tolerance && Mathf.Abs(a.g - b.g) <= tolerance && Mathf.Abs(a.b - b.b) <= tolerance;
        private static bool Dark(Color32 c) => c.r + c.g + c.b < 90;
        private static string Hex(Color32 c) => "#" + ColorUtility.ToHtmlStringRGB(c);

        private static Dictionary<Transform, string> RoleBones(Animator animator)
        {
            var map = new Dictionary<Transform, string>();
            void Add(HumanBodyBones bone, string role) { var t = animator.GetBoneTransform(bone); if (t != null) map[t] = role; }
            foreach (var b in new[] { HumanBodyBones.Head, HumanBodyBones.Neck }) Add(b, "skin");
            foreach (var b in new[] { HumanBodyBones.LeftHand, HumanBodyBones.RightHand }) Add(b, "hand");
            foreach (var b in new[] { HumanBodyBones.LeftFoot, HumanBodyBones.RightFoot, HumanBodyBones.LeftToes, HumanBodyBones.RightToes }) Add(b, "shoes");
            foreach (var b in new[] { HumanBodyBones.Spine, HumanBodyBones.Chest, HumanBodyBones.UpperChest, HumanBodyBones.LeftShoulder, HumanBodyBones.RightShoulder, HumanBodyBones.LeftUpperArm, HumanBodyBones.RightUpperArm, HumanBodyBones.LeftLowerArm, HumanBodyBones.RightLowerArm }) Add(b, "top");
            foreach (var b in new[] { HumanBodyBones.Hips, HumanBodyBones.LeftUpperLeg, HumanBodyBones.RightUpperLeg, HumanBodyBones.LeftLowerLeg, HumanBodyBones.RightLowerLeg }) Add(b, "bottom");
            return map;
        }

        private static string RoleOf(Transform bone, Dictionary<Transform, string> roles)
        {
            for (var t = bone; t != null; t = t.parent) if (roles.TryGetValue(t, out var role)) return role;
            return "";
        }

        private static LookPalette MeasurePalette(string model, string kid, StringBuilder log)
        {
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(KidsCharactersSetup.PrefabFolder + "NL_" + kid + ".prefab");
            if (prefab == null) throw new Exception("Missing kid prefab " + kid);
            var instance = (GameObject)PrefabUtility.InstantiatePrefab(prefab);
            try
            {
                var animator = instance.GetComponentInChildren<Animator>(true);
                var smr = instance.GetComponentsInChildren<SkinnedMeshRenderer>(true).OrderByDescending(r => r.sharedMesh != null ? r.sharedMesh.vertexCount : 0).First();
                var atlasTexture = smr.sharedMaterial.GetTexture("_Texture2D") as Texture2D;
                var atlas = ReadAtlas(AssetDatabase.GetAssetPath(atlasTexture));
                var look = CharacterLook.Models.models.First(m => m.model == model);
                var hair = (Color32)CharacterLook.Hex(look.hairHex);
                var roles = RoleBones(animator);
                var mesh = smr.sharedMesh;
                var uv = mesh.uv;
                var weights = mesh.boneWeights;
                var bones = smr.bones;
                var histogram = new Dictionary<string, Dictionary<int, int>>();
                for (int i = 0; i < uv.Length; i++)
                {
                    var w = weights[i];
                    int best = w.boneIndex0; float bestWeight = w.weight0;
                    if (w.weight1 > bestWeight) { best = w.boneIndex1; bestWeight = w.weight1; }
                    if (w.weight2 > bestWeight) { best = w.boneIndex2; bestWeight = w.weight2; }
                    if (w.weight3 > bestWeight) { best = w.boneIndex3; }
                    string role = RoleOf(best >= 0 && best < bones.Length ? bones[best] : null, roles);
                    if (role == "") continue;
                    int x = Mathf.Clamp(Mathf.FloorToInt(Mathf.Repeat(uv[i].x, 1f) * atlas.width), 0, atlas.width - 1);
                    int y = Mathf.Clamp(Mathf.FloorToInt(Mathf.Repeat(uv[i].y, 1f) * atlas.height), 0, atlas.height - 1);
                    var c = atlas.data[y * atlas.width + x];
                    int key = (c.r << 16) | (c.g << 8) | c.b;
                    if (!histogram.TryGetValue(role, out var roleCounts)) histogram[role] = roleCounts = new Dictionary<int, int>();
                    roleCounts[key] = roleCounts.TryGetValue(key, out var seen) ? seen + 1 : 1;
                }
                if (histogram.TryGetValue("hand", out var handColours)) // hands are skin too
                {
                    if (!histogram.TryGetValue("skin", out var skinColours)) histogram["skin"] = skinColours = new Dictionary<int, int>();
                    foreach (var kv in handColours) skinColours[kv.Key] = skinColours.TryGetValue(kv.Key, out var n0) ? n0 + kv.Value : kv.Value;
                }
                Color32 Unpack(int key) => new Color32((byte)(key >> 16), (byte)(key >> 8), (byte)key, 255);
                IEnumerable<Color32> Ranked(string role, Func<Color32, bool> keep) =>
                    histogram.TryGetValue(role, out var h) ? h.OrderByDescending(kv => kv.Value).Select(kv => Unpack(kv.Key)).Where(c => !Dark(c) && !Near(c, hair) && keep(c)) : Enumerable.Empty<Color32>();

                var skin = Ranked("skin", c => true).FirstOrDefault();
                bool hasSkin = skin.a != 0;
                if (!hasSkin) throw new Exception(model + ": no skin colour found");
                var top = Ranked("top", c => !Near(c, skin, 24)).FirstOrDefault();
                var bottom = Ranked("bottom", c => !Near(c, skin, 24) && (top.a == 0 || !Near(c, top, 24))).FirstOrDefault();
                if (top.a == 0) throw new Exception(model + ": no top colour found");
                // Texels of the whole atlas that would be caught by the recolour: report any other big block that is close.
                var counts = new Dictionary<int, int>();
                foreach (var c in atlas.data) { int key = (c.r << 16) | (c.g << 8) | c.b; counts[key] = counts.TryGetValue(key, out var n) ? n + 1 : 1; }
                var picked = new List<(string role, Color32 colour)> { ("skin", skin), ("top", top) };
                if (bottom.a != 0) picked.Add(("bottom", bottom));
                foreach (var (role, colour) in picked)
                    foreach (var kv in counts.Where(kv => kv.Value >= 150))
                    {
                        var other = Unpack(kv.Key);
                        if (Near(other, colour, 3) || picked.Any(p => Near(other, p.colour, 3))) continue;
                        float d = Vector3.Distance(Linear(other), Linear(colour));
                        if (d < 0.09f) log.AppendLine($"   WARNING {model}: the {role} block {Hex(colour)} is close ({d:0.000}) to another block {Hex(other)} ({kv.Value} px)");
                    }
                log.AppendLine($"{model}: skin {Hex(skin)} (face {look.skinHex}) top {Hex(top)} bottom {(bottom.a != 0 ? Hex(bottom) : "- (one garment)")} hair {Hex(hair)}");
                return new LookPalette { kid = kid, model = model, skinFrom = Hex(skin), topFrom = Hex(top), bottomFrom = bottom.a != 0 ? Hex(bottom) : "" };
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(instance);
            }
        }

        private static Vector3 Linear(Color32 c) { var l = ((Color)c).linear; return new Vector3(l.r, l.g, l.b); }

        private static void BuildMaterial()
        {
            var shader = Shader.Find("Hidden/NihongoLife/PaletteRecolor");
            if (shader == null) throw new Exception("Hidden/NihongoLife/PaletteRecolor shader not found");
            string path = Folder + "NL_PaletteRecolor.mat";
            var existing = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (existing != null) { existing.shader = shader; EditorUtility.SetDirty(existing); }
            else AssetDatabase.CreateAsset(new Material(shader) { name = "NL_PaletteRecolor" }, path);
        }

