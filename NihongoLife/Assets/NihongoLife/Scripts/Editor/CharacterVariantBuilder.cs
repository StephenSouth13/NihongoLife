        private sealed class Placement { public HumanBodyBones bone; public Vector3 position, scale; public Quaternion rotation; public Mesh mesh; public Material material; public string name; }

        private static void BuildPrefabs(CharacterVariantFile file, StringBuilder log)
        {
            var wanted = new HashSet<string>(file.variants.Select(v => "NL_var_" + v.id + ".prefab"));
            foreach (var old in Directory.GetFiles(Folder, "NL_var_*.prefab")) if (!wanted.Contains(Path.GetFileName(old))) AssetDatabase.DeleteAsset(old.Replace('\\', '/'));
            var placements = new Dictionary<string, List<Placement>>(); // kid|uniform
            foreach (var spec in file.variants)
            {
                var kidPrefab = AssetDatabase.LoadAssetAtPath<GameObject>(KidsCharactersSetup.PrefabFolder + "NL_" + spec.kid + ".prefab");
                if (kidPrefab == null) throw new Exception(spec.id + ": unknown kid " + spec.kid);
                var uniform = file.Uniform(spec.uniform);
                if (uniform == null) throw new Exception(spec.id + ": unknown uniform " + spec.uniform);
                string key = spec.kid + "|" + uniform.id;
                if (!placements.TryGetValue(key, out var list)) placements[key] = list = Measure(kidPrefab, uniform);

                var instance = (GameObject)PrefabUtility.InstantiatePrefab(kidPrefab);
                try
                {
                    instance.name = "NL_var_" + spec.id;
                    float s = kidPrefab.transform.localScale.x;
                    instance.transform.localScale = new Vector3(s * spec.girth, s * spec.height, s * spec.girth);
                    var animator = instance.GetComponentInChildren<Animator>(true);
                    foreach (var p in list)
                    {
                        var bone = animator.GetBoneTransform(p.bone);
                        if (bone == null) throw new Exception(spec.id + ": no bone " + p.bone);
                        var go = new GameObject("Uniform_" + p.name, typeof(MeshFilter), typeof(MeshRenderer)) { layer = bone.gameObject.layer };
                        go.transform.SetParent(bone, false);
                        go.transform.localPosition = p.position;
                        go.transform.localRotation = p.rotation;
                        go.transform.localScale = p.scale;
                        go.GetComponent<MeshFilter>().sharedMesh = p.mesh;
                        var renderer = go.GetComponent<MeshRenderer>();
                        renderer.sharedMaterial = p.material;
                        renderer.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.Off;
                    }
                    var component = instance.AddComponent<CharacterVariant>();
                    var so = new SerializedObject(component);
                    so.FindProperty("variantId").stringValue = spec.id;
                    so.ApplyModifiedPropertiesWithoutUndo();
                    PrefabUtility.SaveAsPrefabAsset(instance, Folder + "NL_var_" + spec.id + ".prefab");
                    log.AppendLine($"{spec.id}: {spec.kid} {uniform.id} x{spec.height:0.00}/{spec.girth:0.00} {list.Count} props");
                }
                finally
                {
                    UnityEngine.Object.DestroyImmediate(instance);
                }
            }
        }

        /// <summary>Where each prop of <paramref name="uniform"/> sits on a kid, in the local space of the bone that carries it.
        /// Measured on the kid at its prefab scale (so it holds for any height / girth: the bones carry the scale).</summary>
        private static List<Placement> Measure(GameObject kidPrefab, VariantUniform uniform)
        {
            var result = new List<Placement>();
            var instance = (GameObject)PrefabUtility.InstantiatePrefab(kidPrefab);
            try
            {
                instance.transform.SetPositionAndRotation(Vector3.zero, Quaternion.identity);
                var animator = instance.GetComponentInChildren<Animator>(true);
                var smr = instance.GetComponentsInChildren<SkinnedMeshRenderer>(true).OrderByDescending(r => r.sharedMesh != null ? r.sharedMesh.vertexCount : 0).First();
                var baked = new Mesh();
                smr.BakeMesh(baked, true); // vertices in the renderer's local space; TransformPoint below adds the root scale (checked: height 1.371 m for a 1.35x kid)
                var t = smr.transform;
                var world = baked.vertices.Select(v => t.TransformPoint(v)).ToArray();
                UnityEngine.Object.DestroyImmediate(baked);
                var weights = smr.sharedMesh.boneWeights;
                var roles = RoleBones(animator);
                var roleOfVertex = new string[world.Length];
                var boneOfVertex = new Transform[world.Length];
                for (int i = 0; i < world.Length; i++)
                {
                    var w = weights[i];
                    int best = w.boneIndex0; float bw = w.weight0;
                    if (w.weight1 > bw) { best = w.boneIndex1; bw = w.weight1; }
                    if (w.weight2 > bw) { best = w.boneIndex2; bw = w.weight2; }
                    if (w.weight3 > bw) best = w.boneIndex3;
                    boneOfVertex[i] = best >= 0 && best < smr.bones.Length ? smr.bones[best] : null;
                    roleOfVertex[i] = RoleOf(boneOfVertex[i], roles);
                }
                var head = animator.GetBoneTransform(HumanBodyBones.Head);
                var neck = animator.GetBoneTransform(HumanBodyBones.Neck) ?? head;
                var chest = animator.GetBoneTransform(HumanBodyBones.UpperChest) ?? animator.GetBoneTransform(HumanBodyBones.Chest) ?? animator.GetBoneTransform(HumanBodyBones.Spine);
                var spine = animator.GetBoneTransform(HumanBodyBones.Spine) ?? chest;
                var headBones = new HashSet<Transform>(head.GetComponentsInChildren<Transform>(true));
                // Only what the head bones move (not the shoulders and hands that also lie above the head bone's pivot).
                var headAll = Enumerable.Range(0, world.Length).Where(i => boneOfVertex[i] != null && headBones.Contains(boneOfVertex[i])).ToArray();
                var headIdx = headAll.Where(i => roleOfVertex[i] == "skin").ToArray();
                if (headIdx.Length < 50) headIdx = headAll;
                float hairTop = headAll.Max(i => world[i].y);
                Debug.Log($"[CharacterVariants] {kidPrefab.name} measure: head bone y {head.position.y:0.000} lossy {head.lossyScale} smr lossy {smr.transform.lossyScale} bounds {smr.bounds.size} headVerts {headAll.Length} skinVerts {headIdx.Length}");
                Vector3 min = Vector3.positiveInfinity, max = Vector3.negativeInfinity;
                foreach (int i in headIdx) { min = Vector3.Min(min, world[i]); max = Vector3.Max(max, world[i]); }
                float u = max.x - min.x; // one "head width" (the face)
                Debug.Log($"[CharacterVariants] {kidPrefab.name} u={u:0.000} min={min} max={max} hairTop={hairTop:0.000}");
                var centre = (min + max) * 0.5f;
                max.y = Mathf.Min(hairTop, max.y + 0.2f * u) - 0.22f * u; // hats sit on the hair, sunk in (the skull is lower than the top of the hair)
                float FrontOf(Vector3 around, float halfHeight, float halfWidth, bool front)
                {
                    var zs = Enumerable.Range(0, world.Length).Where(i => (roleOfVertex[i] == "top" || roleOfVertex[i] == "bottom") && Mathf.Abs(world[i].y - around.y) < halfHeight && Mathf.Abs(world[i].x - around.x) < halfWidth).Select(i => world[i].z).ToArray();
                    if (zs.Length == 0) return around.z + (front ? 0.1f : -0.1f) * u;
                    return front ? zs.Max() : zs.Min();
                }
                var anchors = new Dictionary<string, (Vector3 point, HumanBodyBones bone)>
                {
                    ["headTop"] = (new Vector3(centre.x, max.y, centre.z), HumanBodyBones.Head),
                    ["head"] = (centre, HumanBodyBones.Head),
                    ["neck"] = (neck.position, HumanBodyBones.Neck),
                    ["chestFront"] = (new Vector3(chest.position.x, chest.position.y, FrontOf(chest.position, 0.06f * u + 0.02f, 0.45f * u, true)), animator.GetBoneTransform(HumanBodyBones.UpperChest) != null ? HumanBodyBones.UpperChest : animator.GetBoneTransform(HumanBodyBones.Chest) != null ? HumanBodyBones.Chest : HumanBodyBones.Spine),
                    ["chestBack"] = (new Vector3(chest.position.x, chest.position.y, FrontOf(chest.position, 0.06f * u + 0.02f, 0.45f * u, false)), animator.GetBoneTransform(HumanBodyBones.UpperChest) != null ? HumanBodyBones.UpperChest : animator.GetBoneTransform(HumanBodyBones.Chest) != null ? HumanBodyBones.Chest : HumanBodyBones.Spine),
                    ["waistFront"] = (new Vector3(spine.position.x, spine.position.y, FrontOf(spine.position, 0.06f * u + 0.02f, 0.45f * u, true)), HumanBodyBones.Spine),
                };
                if (animator.GetBoneTransform(anchors["headTop"].bone) == null) throw new Exception("no head bone");
                foreach (var piece in uniform.pieces)
                {
                    if (!anchors.TryGetValue(piece.anchor, out var anchor)) throw new Exception(uniform.id + "/" + piece.name + ": unknown anchor " + piece.anchor);
                    var bone = animator.GetBoneTransform(anchor.bone);
                    var mesh = Resources.GetBuiltinResource<Mesh>(piece.shape == "sphere" ? "Sphere.fbx" : piece.shape == "cylinder" ? "Cylinder.fbx" : "Cube.fbx");
                    var go = new GameObject("probe");
                    go.transform.SetPositionAndRotation(anchor.point + new Vector3(piece.pos[0], piece.pos[1], piece.pos[2]) * u, Quaternion.Euler(piece.rot[0], piece.rot[1], piece.rot[2]));
                    var size = new Vector3(piece.size[0], piece.size[1], piece.size[2]) * u;
                    var unit = mesh.bounds.size; // built-in meshes differ in size (a sphere / cylinder is 2 units tall or wide): size is always the finished prop's size
                    go.transform.localScale = new Vector3(size.x / unit.x, size.y / unit.y, size.z / unit.z);
                    go.transform.SetParent(bone, true);
                    result.Add(new Placement
                    {
                        bone = anchor.bone, name = piece.name, mesh = mesh, material = PieceMaterial(piece.hex),
                        position = go.transform.localPosition, rotation = go.transform.localRotation, scale = go.transform.localScale,
                    });
                    UnityEngine.Object.DestroyImmediate(go);
                }
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(instance);
            }
            return result;
        }

        private static Material PieceMaterial(string hex)
        {
            string path = Folder + "Materials/NL_Uniform_" + hex.TrimStart('#').ToUpperInvariant() + ".mat";
            var existing = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (existing != null) return existing;
            var material = new Material(Shader.Find("Universal Render Pipeline/Lit")) { name = Path.GetFileNameWithoutExtension(path) };
            var colour = CharacterLook.Hex(hex);
            material.SetColor("_BaseColor", colour);
            material.color = colour;
            material.SetFloat("_Smoothness", 0.2f);
            AssetDatabase.CreateAsset(material, path);
            return material;
        }
    }
