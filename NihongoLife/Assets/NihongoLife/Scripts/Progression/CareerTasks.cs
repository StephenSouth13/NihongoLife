using System;
using System.Collections.Generic;
using System.Linq;
using NihongoLife.Core;
using NihongoLife.UI;
using UnityEngine;

namespace NihongoLife.Progression
{
    [Serializable]
    public sealed class CareerTaskChoice
    {
        public string vi, en, ja, hintVi, hintEn;
        public bool correct;
        public string Label => Loc.Pick(vi, en, ja);
        public string Hint => Loc.Pick(hintVi, hintEn, string.IsNullOrEmpty(hintEn) ? hintVi : hintEn);
    }

    [Serializable]
    public sealed class CareerTask
    {
        public string id, kind, kindVi, kindEn, kindJa, speaker, ja, meaningVi, meaningEn, askVi, askEn, askJa;
        public int minLevel = 1;
        public CareerTaskChoice[] choices = Array.Empty<CareerTaskChoice>();
        public string Kind => Loc.Pick(kindVi, kindEn, kindJa);
        public string Ask => Loc.Pick(askVi, askEn, askJa);
        public string Meaning => Loc.Pick(meaningVi, meaningEn, meaningVi);
    }

    [Serializable]
    public sealed class CareerTaskLadder
    {
        public int shiftTasks = 4, offHoursTasks = 2, cardsPerShift = 2;
        public int[] tasksPerLevel = Array.Empty<int>();
    }

    /// <summary>
    /// The work of a career, task by task (Resources/Progression/career_tasks.json — the ladder — and CareerTasks/&lt;career&gt;.json,
    /// generated by Tools/story/career_tasks.py; more than 300 different tasks per career). A shift counts its own work as
    /// <see cref="CareerTaskLadder.shiftTasks"/> tasks (half outside working hours), then hands over task cards: a line in
    /// Japanese at the workplace and three answers — right the first time is one more task. A level needs
    /// <see cref="TasksToPromote"/> tasks (more than 300 from level 1 to the top). Cards come in a fixed shuffled order per
    /// career (<see cref="CareerState.taskCursor"/>), so they do not repeat before the pool runs out. Tests keep the cards off
    /// unless they test them (PlayModeSaveGuard).
    /// </summary>
    public static class CareerTasks
    {
        public const string LadderPath = "Progression/career_tasks";
        public const string TaskFolder = "Progression/CareerTasks/";
        public static bool Enabled = true;

        [Serializable]
        private sealed class TaskFile
        {
            public string id, speakerVi, speakerEn, speakerJa;
            public CareerTask[] tasks = Array.Empty<CareerTask>();
        }

        private static CareerTaskLadder _ladder;
        private static TaskFile _file;
        private static int[] _order;

        public static CareerTaskLadder Ladder
        {
            get
            {
                if (_ladder != null) return _ladder;
                var text = Resources.Load<TextAsset>(LadderPath);
                _ladder = text != null ? JsonUtility.FromJson<CareerTaskLadder>(text.text) ?? new CareerTaskLadder() : new CareerTaskLadder();
                return _ladder;
            }
        }

        /// <summary>Tasks that fill the bar at <paramref name="level"/> (1-based).</summary>
        public static int TasksToPromote(int level)
        {
            var steps = Ladder.tasksPerLevel;
            if (steps == null || steps.Length == 0) return 30;
            return Mathf.Max(1, steps[Mathf.Clamp(level - 1, 0, steps.Length - 1)]);
        }

        /// <summary>Tasks from level 1 to the top of this career (every promotion on the way).</summary>
        public static int TasksToTop(CareerDefinition career)
        {
            if (career == null) return 0;
            int total = 0;
            for (int level = 1; level < career.MaxLevel; level++) total += TasksToPromote(level);
            return total;
        }

        /// <summary>Tasks done at the current level, from the bar (the bar may also move by events, stories, missed days).</summary>
        public static int DoneAtLevel(CareerState state) => state == null ? 0 : Mathf.RoundToInt(state.performance / 100f * TasksToPromote(Mathf.Max(1, state.level)));

        /// <summary>The task list of one career (only that career's file is loaded).</summary>
        public static IReadOnlyList<CareerTask> For(string careerId)
        {
            if (string.IsNullOrEmpty(careerId)) return Array.Empty<CareerTask>();
            if (_file == null || _file.id != careerId)
            {
                var text = Resources.Load<TextAsset>(TaskFolder + careerId);
                _file = text != null ? JsonUtility.FromJson<TaskFile>(text.text) ?? new TaskFile { id = careerId } : new TaskFile { id = careerId };
                _file.id = careerId;
                var random = new System.Random(careerId.Aggregate(17, (h, c) => h * 31 + c));
                _order = Enumerable.Range(0, _file.tasks.Length).OrderBy(_ => random.Next()).ToArray();
            }
            return _file.tasks;
        }

        /// <summary>The next card for this level: the career's shuffled order from the saved cursor, skipping cards for higher levels.</summary>
        public static CareerTask Next(string careerId, CareerState state)
        {
            var tasks = For(careerId);
            if (tasks.Count == 0 || state == null) return null;
            int level = Mathf.Max(1, state.level);
            for (int step = 0; step < tasks.Count; step++)
            {
                int index = (state.taskCursor + step) % tasks.Count;
                var task = tasks[_order[index]];
                if (task.minLevel > level) continue;
                state.taskCursor = index + 1;
                return task;
            }
            return null;
        }

        public static string SpeakerName(CareerTask task, CareerDefinition career)
        {
            if (task == null) return string.Empty;
            if (task.speaker == "boss") return career?.BossName ?? string.Empty;
            For(career?.id);
            return _file != null ? Loc.Pick(_file.speakerVi, _file.speakerEn, _file.speakerJa) : string.Empty;
        }

        /// <summary>
        /// Shows <paramref name="count"/> cards one after another; <paramref name="done"/> gets how many were right the first time
        /// (closing a card with Esc ends the round). False when there is nothing to show (no cards, a card already open).
        /// </summary>
        public static bool RunCards(CareerDefinition career, CareerState state, int count, Action<int> done)
        {
            if (!Enabled || career == null || state == null || count <= 0 || JobQuizCard.IsOpen) return false;
            var first = Next(career.id, state);
            if (first == null) return false;
            int right = 0;
            void Show(CareerTask task, int left)
            {
                var choices = task.choices.Select((c, i) => new JobQuizCard.Choice { Id = i.ToString(), Label = c.Label, Correct = c.correct, WrongHint = c.Hint }).ToList();
                string kicker = Loc.F("VIỆC TRONG CA · {0} · {1}/{2}", "SHIFT TASK · {0} · {1}/{2}", "仕事 · {0} · {1}/{2}", task.Kind, count - left + 1, count);
                string line = string.IsNullOrEmpty(task.ja) ? task.Ask : task.ja;
                string question = string.IsNullOrEmpty(task.ja) ? Loc.T("Chọn câu tiếng Nhật đúng.", "Pick the right Japanese.", "正しい日本語を選んでください。") : task.Ask;
                JobQuizCard.Show(kicker, SpeakerName(task, career), line, null, string.IsNullOrEmpty(task.ja) ? null : task.Meaning, question, choices, _ =>
                {
                    if (JobQuizCard.LastMistakes == 0) right++;
                    var next = left > 1 ? Next(career.id, state) : null;
                    if (next != null) Show(next, left - 1);
                    else done?.Invoke(right);
                });
                JobQuizCard.OnClosedWithoutAnswer = () => done?.Invoke(right);
            }
            Show(first, count);
            return true;
        }
    }
}
