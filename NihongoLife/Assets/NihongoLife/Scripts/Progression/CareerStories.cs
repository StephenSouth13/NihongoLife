using System;
using System.Collections.Generic;
using System.Linq;
using NihongoLife.Core;
using NihongoLife.Dialogue;
using NihongoLife.Player;
using NihongoLife.Scenario;
using NihongoLife.UI;
using UnityEngine;

namespace NihongoLife.Progression
{
    [Serializable] public sealed class CareerStoryCast { public string id, vi, en, ja; }
    [Serializable] public sealed class CareerStoryLine { public string speaker, ja, vi, en; }

    [Serializable]
    public sealed class CareerStoryChoice
    {
        public string id, kind, ja, vi, en, mood;
        public CareerStoryLine reply;
        public int performance, reputation, knowledge;
    }

    [Serializable]
    public sealed class CareerStory
    {
        public string id, career, branch, titleVi, titleEn, titleJa;
        public int toLevel;
        public CareerStoryCast[] cast = Array.Empty<CareerStoryCast>();
        public CareerStoryLine[] lines = Array.Empty<CareerStoryLine>();
        public CareerStoryLine ask;
        public CareerStoryChoice[] choices = Array.Empty<CareerStoryChoice>();
        public string Title => Loc.Pick(titleVi, titleEn, titleJa);
    }

    /// <summary>
    /// A milestone story before each promotion interview (Resources/Progression/career_stories.json, generated by
    /// Tools/story/career_stories.py): a short scene at the workplace in the shared dialogue UI, a question and three
    /// answers in Japanese. The best answer gives trí tuệ and reputation; a poor one costs performance, so the bar is
    /// no longer full and the interview waits for the next shift. Each story plays once (CareerState.stories); leaving it
    /// with Esc plays it again next time. Tests keep it off unless they test it (PlayModeSaveGuard).
    /// </summary>
    public static class CareerStories
    {
        public const string ResourcePath = "Progression/career_stories";
        private const string ChoicePrefix = "story_choice:";
        public static bool Enabled = true;

        [Serializable] private sealed class StoryFile { public CareerStory[] stories = Array.Empty<CareerStory>(); }
        private static CareerStory[] _all;

        public static IReadOnlyList<CareerStory> All
        {
            get
            {
                if (_all == null)
                {
                    var text = Resources.Load<TextAsset>(ResourcePath);
                    _all = text != null ? (JsonUtility.FromJson<StoryFile>(text.text)?.stories ?? Array.Empty<CareerStory>()) : Array.Empty<CareerStory>();
                }
                return _all;
            }
        }

        /// <summary>The story of the promotion to <paramref name="toLevel"/> (the shared one, or the branch's).</summary>
        public static CareerStory Find(string careerId, int toLevel, string branchId) =>
            All.FirstOrDefault(s => s.career == careerId && s.toLevel == toLevel && s.branch == (branchId ?? string.Empty))
            ?? All.FirstOrDefault(s => s.career == careerId && s.toLevel == toLevel && string.IsNullOrEmpty(s.branch));

        /// <summary>The story still to play before this promotion's interview, or null.</summary>
        public static CareerStory Pending(CareerDefinition career, CareerState state)
        {
            if (!Enabled || career == null || state == null) return null;
            var story = Find(career.id, state.level + 1, state.branchId);
            return story != null && !state.stories.Contains(story.id) ? story : null;
        }

        /// <summary>Plays the story; <paramref name="finished"/> gets the chosen answer (null when the player left with Esc).
        /// False when the dialogue UI is not there or busy (the story waits for the next shift).</summary>
        public static bool Play(CareerStory story, CareerDefinition career, Action<CareerStoryChoice> finished)
        {
            var dm = DialogueManager.Instance;
            if (story == null || dm == null || dm.IsOpen) return false;
            var nodes = BuildNodes(story, career);
            dm.StartConversation(nodes, nodes[0].id, end =>
            {
                var chosen = end != null && end.StartsWith(ChoicePrefix, StringComparison.Ordinal)
                    ? story.choices.FirstOrDefault(c => c.id == end.Substring(ChoicePrefix.Length)) : null;
                finished?.Invoke(chosen);
            });
            return true;
        }

        /// <summary>Lines → question (answers) → the reply to the chosen answer, which ends on "story_choice:&lt;id&gt;".</summary>
        public static List<ScenarioNode> BuildNodes(CareerStory story, CareerDefinition career)
        {
            var nodes = new List<ScenarioNode>();
            string Id(string part) => "cs_" + story.id + "_" + part;
            for (int i = 0; i < story.lines.Length; i++) nodes.Add(Node(story, career, Id("l" + i), story.lines[i]));
            var ask = Node(story, career, Id("ask"), story.ask);
            nodes.Add(ask);
            for (int i = 0; i + 1 < nodes.Count; i++) nodes[i].nextNodeId = nodes[i + 1].id;
            foreach (var c in story.choices)
            {
                var reply = Node(story, career, Id("r_" + c.id), c.reply);
                reply.nextNodeId = ChoicePrefix + c.id;
                nodes.Add(reply);
                ask.choices.Add(new DialogueChoice { textJa = c.ja, textVi = c.vi, textEn = c.en, nextNodeId = reply.id });
            }
            return nodes;
        }

        private static ScenarioNode Node(CareerStory story, CareerDefinition career, string id, CareerStoryLine line) => new ScenarioNode
        {
            id = id, nodeType = ScenarioNodeType.Dialogue,
            speakerName = SpeakerName(story, career, line.speaker),
            textJa = line.ja, textVi = line.vi, textEn = line.en,
        };

        public static string SpeakerName(CareerStory story, CareerDefinition career, string speaker)
        {
            if (speaker == "narrator") return string.Empty;
            if (speaker == "boss") return career?.BossName ?? string.Empty;
            var cast = story.cast.FirstOrDefault(c => c.id == speaker);
            return cast != null ? Loc.Pick(cast.vi, cast.en, cast.ja) : speaker;
        }

        /// <summary>The consequence of an answer: performance, reputation or notoriety, trí tuệ, a mood.</summary>
        public static void Apply(CareerStoryChoice choice, CareerState state)
        {
            if (choice == null || state == null) return;
            state.performance = Mathf.Clamp(state.performance + choice.performance, 0f, 100f);
            if (choice.reputation > 0) SocialStanding.AddReputation(choice.reputation, "career_story");
            else if (choice.reputation < 0) SocialStanding.AddNotoriety(-choice.reputation, "career_story");
            if (choice.knowledge > 0) PlayerStatus.Instance?.AddKnowledge(choice.knowledge);
            if (!string.IsNullOrEmpty(choice.mood) && Enum.TryParse(choice.mood, out SocialMood mood)) SocialStanding.AddMoodlet("career_story", mood, 0.5f, 3f);
            string result = choice.kind == "best"
                ? Loc.F("Câu trả lời rất tốt · +{0} trí tuệ", "A great answer · +{0} knowledge", "すばらしい答え · 知識 +{0}", choice.knowledge)
                : choice.kind == "poor"
                    ? Loc.F("Câu trả lời chưa tốt · hiệu suất {0} → {1:0}%: phỏng vấn để lần sau", "Not a good answer · performance {0} → {1:0}%: the interview waits", "よくない答え · 評価 {0} → {1:0}%：面接は次回に", choice.performance, state.performance)
                    : Loc.T("Câu trả lời tạm được", "An okay answer", "まあまあの答え");
            HudFeed.Post(result, choice.kind == "poor" ? HudFeed.Kind.Warning : HudFeed.Kind.Reward, 6f, "career-story");
        }
    }
}
