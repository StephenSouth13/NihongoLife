using System.Collections;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using NihongoLife.Gestures;
using NUnit.Framework;
using UnityEngine;
using UnityEngine.TestTools;

namespace NihongoLife.Tests
{
    /// <summary>
    /// Photographs every gesture: one contact sheet per gesture (six moments, a 3/4 view) in Bao_Cao/gestures, plus an INDEX.md
    /// with names in four languages. Each sheet is checked for content (the character is drawn) and for motion (frames differ).
    /// </summary>
    public class GestureCapturePlayModeTests : GestureTestBase
    {
        private const int W = 240, H = 320, Frames = 6;
        private static string Root => Path.GetFullPath(Path.Combine(Application.dataPath, "../../Bao_Cao/gestures"));

        private static Texture2D Shoot(Camera cam, RenderTexture rt)
        {
            cam.targetTexture = rt; cam.Render();
            var old = RenderTexture.active; RenderTexture.active = rt;
            var tex = new Texture2D(W, H, TextureFormat.RGB24, false);
            tex.ReadPixels(new Rect(0, 0, W, H), 0, 0); tex.Apply();
            RenderTexture.active = old;
            return tex;
        }

        private static float Diff(Texture2D a, Texture2D b)
        {
            var pa = a.GetPixels32(); var pb = b.GetPixels32(); long sum = 0;
            for (int i = 0; i < pa.Length; i++) sum += Mathf.Abs(pa[i].r - pb[i].r) + Mathf.Abs(pa[i].g - pb[i].g) + Mathf.Abs(pa[i].b - pb[i].b);
            return sum / (3f * 255f * pa.Length);
        }

        private static float Coverage(Texture2D t, Color32 bg)
        {
            var p = t.GetPixels32(); int n = 0;
            foreach (var c in p) if (Mathf.Abs(c.r - bg.r) + Mathf.Abs(c.g - bg.g) + Mathf.Abs(c.b - bg.b) > 40) n++;
            return n / (float)p.Length;
        }

        // A UnityTest: each shot is taken in its own frame, because the skinned meshes are only re-skinned once per frame.
        [UnityTest]
        public IEnumerator EveryGesture_IsPhotographed_AndMoves()
        {
            Directory.CreateDirectory(Root);
            foreach (var f in Directory.GetFiles(Root, "*.png")) File.Delete(f);
            var person = Person(FirstVariant, Vector3.zero, out var layer);
            var camGo = new GameObject("GestureCam");
            UnityEngine.SceneManagement.SceneManager.MoveGameObjectToScene(camGo, Scene);
            Spawned.Add(camGo);
            var cam = camGo.AddComponent<Camera>();
            cam.clearFlags = CameraClearFlags.SolidColor; cam.backgroundColor = new Color(0.78f, 0.84f, 0.92f);
            cam.fieldOfView = 32f; cam.nearClipPlane = 0.1f; cam.farClipPlane = 60f; cam.aspect = W / (float)H;
            var rt = new RenderTexture(W, H, 24, RenderTextureFormat.ARGB32);
            Tick(layer, 30);
            var bounds = person.GetComponentsInChildren<SkinnedMeshRenderer>().Select(r => r.bounds).Aggregate((a, b) => { a.Encapsulate(b); return a; });
            var center = new Vector3(0f, bounds.center.y, 0.3f);
            float dist = bounds.size.y * 1.05f / Mathf.Tan(cam.fieldOfView * 0.5f * Mathf.Deg2Rad) * 0.62f + 1.1f;
            cam.transform.position = center + new Vector3(Mathf.Sin(35f * Mathf.Deg2Rad), 0.08f, Mathf.Cos(35f * Mathf.Deg2Rad)) * dist;
            cam.transform.LookAt(center);

            var index = new StringBuilder("# Gesture library - contact sheets\n\nSix moments per gesture, 3/4 view. Generated by GestureCapturePlayModeTests.\n\n| id | category | vi | en | ja | ru | seconds | loop |\n|---|---|---|---|---|---|---|---|\n");
            var failures = new List<string>();
            var bg = (Color32)cam.backgroundColor;
            int sheets = 0;
            foreach (var def in GestureLibrary.All)
            {
                layer.Play(def.id);
                var sheet = new Texture2D(W * Frames, H, TextureFormat.RGB24, false);
                Texture2D prev = null; float motion = 0f, coverage = 1f;
                Vector3 h0 = Bone(layer, HumanBodyBones.RightHand), h1 = Bone(layer, HumanBodyBones.LeftHand); float handMove = 0f;
                float span = def.loop ? def.dur : def.dur * 0.92f;
                int last = 0;
                for (int f = 0; f < Frames; f++)
                {
                    int target = Mathf.RoundToInt((0.08f + 0.84f * f / (Frames - 1)) * span / Dt);
                    Tick(layer, Mathf.Max(1, target - last)); last = target;
                    yield return null;
                    var shot = Shoot(cam, rt);
                    handMove = Mathf.Max(handMove, (Bone(layer, HumanBodyBones.RightHand) - h0).magnitude, (Bone(layer, HumanBodyBones.LeftHand) - h1).magnitude);
                    sheet.SetPixels(f * W, 0, W, H, shot.GetPixels());
                    coverage = Mathf.Min(coverage, Coverage(shot, bg));
                    if (prev != null) { motion = Mathf.Max(motion, Diff(prev, shot)); Object.Destroy(prev); }
                    prev = shot;
                }
                Object.Destroy(prev);
                sheet.Apply();
                File.WriteAllBytes(Path.Combine(Root, def.id + ".png"), sheet.EncodeToPNG());
                Object.Destroy(sheet);
                sheets++;
                if (coverage < 0.03f) failures.Add(def.id + " frame is empty (coverage " + coverage.ToString("0.000") + ")");
                if (motion < 0.001f) failures.Add(def.id + " does not move (diff " + motion.ToString("0.0000") + ", hand bones moved " + handMove.ToString("0.000") + " m, timeScale " + Time.timeScale + ", playing " + layer.IsPlaying + ")");
                index.AppendLine("| " + def.id + " | " + def.cat + " | " + def.vi + " | " + def.en + " | " + def.ja + " | " + def.ru + " | " + def.dur.ToString("0.0") + " | " + (def.loop ? "yes" : "no") + " |");
                layer.Stop(0f); Tick(layer, 40);
            }
            File.WriteAllText(Path.Combine(Root, "INDEX.md"), index.ToString(), new UTF8Encoding(false));
            Object.Destroy(rt);
            Assert.AreEqual(GestureLibrary.All.Count, sheets);
            Assert.IsEmpty(failures, string.Join("\n", failures));
        }
    }
}